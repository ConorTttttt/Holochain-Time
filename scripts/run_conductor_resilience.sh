#!/usr/bin/env bash
# Sprint 12: real Holochain Sweettest conductor restart/isolation/rejoin tests.
# Read-only to the current Git branch; produces a throwaway DNA and log bundle.
set -euo pipefail
usage() {
  cat <<'TEXT'
Usage: HC_VTIME_EXPECTED_SHA=$(git rev-parse HEAD) bash scripts/run_conductor_resilience.sh [--full]
  Default: real 3-conductor restart, missing witness, peer-isolation/rejoin.
  --full: also run expensive 256-action boundary and destructive test-only fork fixture.
Requires Holochain 0.7 Holonix (cargo, rustc, hc), wasm32 target, Python and git.
Never use production keys or real funds. Results are not release approval.
TEXT
}
FULL=0
case "${1:-}" in
  '') ;;
  --full) FULL=1;;
  --help|-h) usage; exit 0;;
  *) usage >&2; exit 2;;
esac
[[ $# -le 1 ]] || { usage >&2; exit 2; }
for cmd in git cargo rustc hc python3 sha256sum tee; do
  command -v "$cmd" >/dev/null || { echo "BLOCKED: missing $cmd" >&2; exit 2; }
done
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SHA=$(git -C "$ROOT" rev-parse --verify HEAD)
EXPECTED=$(printenv HC_VTIME_EXPECTED_SHA || true)
[[ -z "$EXPECTED" || "$SHA" == "$EXPECTED" ]] || {
  echo "BLOCKED: wrong commit SHA, expected $EXPECTED actual $SHA" >&2; exit 4;
}
[[ -z "$(git -C "$ROOT" status --porcelain --untracked-files=all)" ]] || {
  echo 'BLOCKED: dirty checkout. Use a clean, exact-commit clone.' >&2; exit 4;
}
[[ -f "$ROOT/integration/conductor/Cargo.lock" ]] || {
  echo 'BLOCKED: standalone conductor Cargo.lock missing; pin it before acceptance' >&2; exit 3;
}
if [[ ! -f "$ROOT/target/wasm32-unknown-unknown/release/vtime_integrity.wasm" ]]; then
  echo 'WASM needs a reproducible rebuild before packing the test DNA.'
fi
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
REPORT="$(dirname "$ROOT")/hc-vtime-resilience-${SHA:0:12}-$STAMP-$$"
TEMP=$(mktemp -d "${TMPDIR:-/tmp}/hc-vtime-resilience-XXXXXXXX")
# Git worktree requires a non-existent path (it creates the directory itself).
rmdir "$TEMP"
mkdir -p "$REPORT"
printf 'commit=%s\nscope=Sprint12 real conductor resilience\nrelease_approved=false\nmode=%s\n' \
  "$SHA" "$( ((FULL)) && echo full || echo baseline )" > "$REPORT/provenance.txt"
finish() {
  local code=$?
  trap - EXIT
  echo "exit_code=$code" >> "$REPORT/provenance.txt"
  if [[ -d "$REPORT" ]]; then
    (cd "$REPORT" && sha256sum provenance.txt *.log keys-public.json dna.yaml vtime.dna > SHA256SUMS 2>/dev/null) || true
  fi
  git -C "$ROOT" worktree remove --force "$TEMP" >/dev/null 2>&1 || true
  echo "Resilience evidence: $REPORT (exit=$code)" >&2
}
trap finish EXIT
{
  echo "started_utc=$(date -u +%FT%TZ)"
  echo "rustc=$(rustc --version)"
  echo "cargo=$(cargo --version)"
  echo "hc=$(hc --version 2>&1 | tail -1)"
  echo "workspace_lock_sha256=$(sha256sum "$ROOT/Cargo.lock" | cut -d' ' -f1)"
  echo "conductor_lock_sha256=$(sha256sum "$ROOT/integration/conductor/Cargo.lock" | cut -d' ' -f1)"
} >> "$REPORT/provenance.txt"
(
  cd "$ROOT"
  RUSTFLAGS='--cfg getrandom_backend="custom" -C link-arg=--import-undefined' \
    cargo build --release --locked --target wasm32-unknown-unknown -p vtime_integrity -p vtime
) 2>&1 | tee "$REPORT/wasm-build.log"
echo "integrity_wasm_sha256=$(sha256sum "$ROOT/target/wasm32-unknown-unknown/release/vtime_integrity.wasm" | cut -d' ' -f1)" >> "$REPORT/provenance.txt"
echo "coordinator_wasm_sha256=$(sha256sum "$ROOT/target/wasm32-unknown-unknown/release/vtime.wasm" | cut -d' ' -f1)" >> "$REPORT/provenance.txt"
git -C "$ROOT" worktree add --quiet --detach "$TEMP" "$SHA"
ln -s "$ROOT/target" "$TEMP/target"
# Public test-only signing keys, generated by the same Roughenough 2.2 code
# used in the signed-quorum conductor harness. Never write secret keys to logs.
cargo run --manifest-path "$ROOT/integration/conductor/Cargo.toml" --locked \
  --bin signed_test_keys --quiet > "$REPORT/keys-public.json" 2> "$REPORT/keys-build.log"
python3 "$TEMP/scripts/make_signed_test_manifest.py" \
  --template "$TEMP/dnas/vtime/workdir/dna.yaml" \
  --fixture-json "$REPORT/keys-public.json" \
  --out "$TEMP/dnas/vtime/workdir/dna.yaml" 2>&1 | tee "$REPORT/manifest-generation.log"
python3 "$TEMP/scripts/check_test_dna_config.py" \
  --manifest "$TEMP/dnas/vtime/workdir/dna.yaml" 2>&1 | tee "$REPORT/dna-preflight.log"
cp "$TEMP/dnas/vtime/workdir/dna.yaml" "$REPORT/dna.yaml"
(cd "$TEMP" && hc dna pack dnas/vtime/workdir) 2>&1 | tee "$REPORT/dna-pack.log"
cp "$TEMP/dnas/vtime/workdir/vtime.dna" "$REPORT/vtime.dna"
export HC_VTIME_TEST_DNA="$TEMP/dnas/vtime/workdir/vtime.dna"
export HC_VTIME_SIGNED_TEST_ONLY=1
# Real tests run serially to avoid accidental conflicting source-chain writes.
cd "$ROOT"
cargo test --manifest-path integration/conductor/Cargo.toml --locked --test resilience \
  -- --nocapture --test-threads=1 2>&1 | tee "$REPORT/resilience-baseline.log"
if ((FULL)); then
  cargo test --manifest-path integration/conductor/Cargo.toml --locked --test resilience \
    ancestry_256_action_budget_enforced_in_conductor -- --ignored --nocapture --test-threads=1 \
    2>&1 | tee "$REPORT/resilience-ancestry.log"
  cargo test --manifest-path integration/conductor/Cargo.toml --locked --test resilience \
    same_agent_two_conductor_fork_does_not_become_trusted -- --ignored --nocapture --test-threads=1 \
    2>&1 | tee "$REPORT/resilience-fork.log"
fi
python3 "$ROOT/scripts/audit_conductor_resilience.py" --report "$REPORT" \
  $( ((FULL)) && echo --require-full || true ) \
  2>&1 | tee "$REPORT/resilience-audit.log"
