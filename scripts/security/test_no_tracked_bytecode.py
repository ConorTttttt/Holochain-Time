#!/usr/bin/env python3
"""Generated Python bytecode must never be tracked source.

Tracked timestamp-mode .pyc files were rewritten by test runs on fresh
checkouts (their recorded source mtimes no longer matched), which dirtied the
exact-commit worktree and blocked later acceptance gates. They are also opaque
to source review: an unchecked-hash .pyc would run without consulting its
reviewed .py source at all.
"""
from pathlib import Path
import subprocess
import unittest

REPO = Path(__file__).resolve().parents[2]


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(REPO), *args],
                          capture_output=True, text=True, timeout=60)


@unittest.skipUnless((REPO / ".git").exists(), "requires a Git checkout of the repository")
class TrackedBytecodeTests(unittest.TestCase):
    def test_no_bytecode_is_tracked(self):
        tracked = git("ls-files", "-z").stdout.split("\0")
        bytecode = [p for p in tracked
                    if p.endswith((".pyc", ".pyo")) or "/__pycache__/" in f"/{p}"]
        self.assertEqual(bytecode, [], "generated bytecode must not be committed")

    def test_bytecode_paths_are_ignored(self):
        for path in ("scripts/__pycache__/x.cpython-314.pyc",
                     "scripts/license37/__pycache__/y.cpython-314.pyc",
                     "crates/tool.pyc"):
            with self.subTest(path=path):
                self.assertEqual(git("check-ignore", "-q", "--no-index", path).returncode, 0,
                                 f"{path} is not ignored")


if __name__ == "__main__":
    unittest.main()
